def is_keyword(word: str) -> bool:
    return word.lower() in _KEYWORDS


def words(text: str) -> list[str]:
    """`OrderItem` / `order item` / `ORDER_ITEM` -> ["order", "item"]."""
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", text)
    return [w.lower() for w in re.split(r"[\s_\-/]+", text) if w]


def camel(ws: list[str]) -> str:
    return ws[0] + "".join(w[:1].upper() + w[1:] for w in ws[1:]) if ws else ""


def pascal(ws: list[str]) -> str:
    return "".join(w[:1].upper() + w[1:] for w in ws)


def snake(ws: list[str]) -> str:
    return "_".join(ws)


def ident(text: str) -> str:
    """A PascalCase identifier for a spaced name ("Orders DB" -> "OrdersDB")."""
    out = "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", text) if w)
    return out if out and not out[0].isdigit() and not is_keyword(out) else f"X{out}"


def pick_domain(rng: random.Random) -> Domain:
    return rng.choice(DOMAINS)


def sample_unique(rng: random.Random, pool, k: int, taken: set[str]) -> list[str]:
    """Up to k items of `pool` that are not in `taken` (case-insensitive) and not keywords."""
    cands = [x for x in pool if x.lower() not in taken and not is_keyword(x)]
    rng.shuffle(cands)
    out = cands[:k]
    taken.update(x.lower() for x in out)
    return out
